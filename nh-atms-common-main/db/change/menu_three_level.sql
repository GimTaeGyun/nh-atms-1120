-- 메뉴ID 3단계 이관 — 견본 메뉴 SMP000·SMP001~ → SMP0000(대)·SMP0100(중 '견본 화면')·SMP0101~(소) + 메뉴관리 메뉴 행
-- 규칙(2026-11-12 사용자 결정, 서버 MenuMgtRules): 메뉴ID = 영문 대문자 3 + 중메뉴 번호 2 + 소메뉴 번호 2 (SYS0000 대 · SYS0300 중 · SYS0312 소)
-- 폐쇄망 개발 DB 에서 처음 확인 필요. 한 문장씩 실행하고 마지막에 COMMIT. 다시 돌려도 같은 결과(NOT EXISTS · REGEXP_LIKE 조건).
-- <내 개인번호> 는 실행하는 사람의 개인번호(9자 이내)로 바꾼다. 권한별 메뉴(TB_SCR_AUTH_MENU) 행도 같은 메뉴ID 로 옮긴다.
-- 화면 권한 검사는 MENU_PATH 로 메뉴를 찾으므로(MenuAuthService) 메뉴ID 가 바뀌어도 경로가 같으면 권한은 그대로다.

-- 0) 지금 상태 보기 (읽기만)
SELECT MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN FROM TB_SCR_MENU WHERE MENU_ID LIKE 'SMP%' ORDER BY MENU_ID;

SELECT AUTH, MENU_ID, QRY_ROL_YN, USE_YN FROM TB_SCR_AUTH_MENU WHERE MENU_ID LIKE 'SMP%' ORDER BY AUTH, MENU_ID;

-- 1) 대메뉴 SMP0000 — 예전 SMP000 행을 그대로 복사(이름·순서·사용여부 유지)
INSERT INTO TB_SCR_MENU (MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN, CRT_DTM, CRT_CMENO, LSCHG_DTM, LS_CMENO)
SELECT 'SMP0000', PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN, CRT_DTM, CRT_CMENO, TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>'
  FROM TB_SCR_MENU
 WHERE MENU_ID = 'SMP000'
   AND NOT EXISTS (SELECT 1 FROM TB_SCR_MENU WHERE MENU_ID = 'SMP0000');

-- 2) 중메뉴 SMP0100 '견본 화면' — 새로 넣음(그룹 G, 경로 없음, 순서 1)
INSERT INTO TB_SCR_MENU (MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN, CRT_DTM, CRT_CMENO, LSCHG_DTM, LS_CMENO)
SELECT 'SMP0100', 'SMP0000', '견본 화면', 'G', NULL, 1, 'Y',
       TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>', TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>'
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM TB_SCR_MENU WHERE MENU_ID = 'SMP0100');

-- 3) 소메뉴 SMP001~SMP099 → SMP0101~SMP0199 (이름·경로·순서·사용여부 유지, 상위 = SMP0100)
INSERT INTO TB_SCR_MENU (MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN, CRT_DTM, CRT_CMENO, LSCHG_DTM, LS_CMENO)
SELECT 'SMP01' || SUBSTR(M.MENU_ID, 5, 2), 'SMP0100', M.MENU_NM, M.MENU_TYPE, M.MENU_PATH, M.SORT_NO, M.USE_YN, M.CRT_DTM, M.CRT_CMENO, TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>'
  FROM TB_SCR_MENU M
 WHERE REGEXP_LIKE(M.MENU_ID, '^SMP0[0-9]{2}$')
   AND M.MENU_ID <> 'SMP000'
   AND NOT EXISTS (SELECT 1 FROM TB_SCR_MENU X WHERE X.MENU_ID = 'SMP01' || SUBSTR(M.MENU_ID, 5, 2));

-- 4) 권한별 메뉴 행의 메뉴ID 를 새 ID 로
UPDATE TB_SCR_AUTH_MENU
   SET MENU_ID = CASE WHEN MENU_ID = 'SMP000' THEN 'SMP0000' ELSE 'SMP01' || SUBSTR(MENU_ID, 5, 2) END,
       LSCHG_DTM = TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'),
       LS_CMENO = '<내 개인번호>'
 WHERE REGEXP_LIKE(MENU_ID, '^SMP0[0-9]{2}$');

-- 5) 예전 6자리 메뉴 행 지우기
DELETE FROM TB_SCR_MENU WHERE REGEXP_LIKE(MENU_ID, '^SMP0[0-9]{2}$');

-- 6) 메뉴관리 화면 메뉴 행 — '견본 화면' 아래 소메뉴, 번호 = MAX + 1 (같은 경로가 이미 있으면 넣지 않음)
INSERT INTO TB_SCR_MENU (MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN, CRT_DTM, CRT_CMENO, LSCHG_DTM, LS_CMENO)
SELECT 'SMP01' || LPAD(X.N + 1, 2, '0'), 'SMP0100', '메뉴관리', 'M', '/sample/menu-mgt', X.S + 1, 'Y',
       TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>', TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>'
  FROM (SELECT NVL(MAX(TO_NUMBER(SUBSTR(MENU_ID, 6, 2))), 0) AS N, NVL(MAX(SORT_NO), 0) AS S
          FROM TB_SCR_MENU
         WHERE PARENT_MENU_ID = 'SMP0100'
           AND REGEXP_LIKE(MENU_ID, '^SMP01[0-9]{2}$')) X
 WHERE NOT EXISTS (SELECT 1 FROM TB_SCR_MENU WHERE MENU_PATH = '/sample/menu-mgt');

-- 7) 확인 — SMP0000 · SMP0100 · SMP0101~ 만 남고, 권한별 메뉴 행도 새 ID 인지
SELECT MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN FROM TB_SCR_MENU WHERE MENU_ID LIKE 'SMP%' ORDER BY MENU_ID;

SELECT AUTH, MENU_ID, QRY_ROL_YN, USE_YN FROM TB_SCR_AUTH_MENU WHERE MENU_ID LIKE 'SMP%' ORDER BY AUTH, MENU_ID;

COMMIT;
