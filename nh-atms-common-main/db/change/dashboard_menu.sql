-- 대시보드 메뉴 행 — 대메뉴 DSB0000 '대시보드'(상단 첫 칸) → 중메뉴 DSB0100 '대시보드' → 소메뉴 DSB0101 '대시보드'(경로 /main/dashboard)
-- 2026-11-16 사용자 결정: 대시보드를 메뉴(화면키 main.dashboard)로 등록해 권한관리의 조회(QRY) 권한으로 막는다.
-- 홈 탭이 이 화면이다. 권한 A·T·L 에 조회만 준다(다른 권한코드는 권한관리 → 메뉴 권한 탭에서 체크).
-- 폐쇄망 개발 DB 에서 처음 확인 필요. 한 문장씩 실행하고 마지막에 COMMIT. 다시 돌려도 같은 결과(NOT EXISTS 조건).
-- <내 개인번호> 는 실행하는 사람의 개인번호(9자 이내)로 바꾼다. 상단 순서(SORT_NO 10)는 다른 대메뉴보다 앞이 되게 — 필요하면 메뉴관리 화면에서 바꾼다.
-- 0) 지금 상태 보기 (읽기만) — DSB 접두어·/main/dashboard 경로가 이미 있는지
SELECT MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN FROM TB_SCR_MENU WHERE MENU_ID LIKE 'DSB%' OR MENU_PATH = '/main/dashboard' ORDER BY MENU_ID;
-- 1) 대메뉴
INSERT INTO TB_SCR_MENU (MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN, CRT_DTM, CRT_CMENO, LSCHG_DTM, LS_CMENO)
SELECT 'DSB0000', '0', '대시보드', 'G', NULL, 10, 'Y',
       TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>', TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>'
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM TB_SCR_MENU WHERE MENU_ID = 'DSB0000');
-- 2) 중메뉴
INSERT INTO TB_SCR_MENU (MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN, CRT_DTM, CRT_CMENO, LSCHG_DTM, LS_CMENO)
SELECT 'DSB0100', 'DSB0000', '대시보드', 'G', NULL, 1, 'Y',
       TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>', TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>'
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM TB_SCR_MENU WHERE MENU_ID = 'DSB0100');
-- 3) 소메뉴(화면) — 같은 경로가 이미 있으면 넣지 않음
INSERT INTO TB_SCR_MENU (MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN, CRT_DTM, CRT_CMENO, LSCHG_DTM, LS_CMENO)
SELECT 'DSB0101', 'DSB0100', '대시보드', 'M', '/main/dashboard', 1, 'Y',
       TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>', TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>'
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM TB_SCR_MENU WHERE MENU_ID = 'DSB0101' OR MENU_PATH = '/main/dashboard');
-- 4) 권한 A·T·L 에 조회(QRY)만 — 대메뉴·중메뉴·소메뉴 행 모두(이미 있으면 넣지 않음)
INSERT INTO TB_SCR_AUTH_MENU (AUTH, MENU_ID, QRY_ROL_YN, REG_ROL_YN, UPD_ROL_YN, DEL_ROL_YN, EXE_ROL_YN, USE_YN, CRT_DTM, CRT_CMENO, LSCHG_DTM, LS_CMENO)
SELECT A.AUTH, M.MENU_ID, 'Y', 'N', 'N', 'N', 'N', 'Y',
       TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>', TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS'), '<내 개인번호>'
  FROM (SELECT 'A' AS AUTH FROM DUAL UNION ALL SELECT 'T' FROM DUAL UNION ALL SELECT 'L' FROM DUAL) A
 CROSS JOIN (SELECT MENU_ID FROM TB_SCR_MENU WHERE MENU_ID IN ('DSB0000', 'DSB0100', 'DSB0101')) M
 WHERE NOT EXISTS (SELECT 1 FROM TB_SCR_AUTH_MENU X WHERE X.AUTH = A.AUTH AND X.MENU_ID = M.MENU_ID);
-- 5) 확인
SELECT MENU_ID, PARENT_MENU_ID, MENU_NM, MENU_TYPE, MENU_PATH, SORT_NO, USE_YN FROM TB_SCR_MENU WHERE MENU_ID LIKE 'DSB%' ORDER BY MENU_ID;
SELECT AUTH, MENU_ID, QRY_ROL_YN, USE_YN FROM TB_SCR_AUTH_MENU WHERE MENU_ID LIKE 'DSB%' ORDER BY AUTH, MENU_ID;
COMMIT;
